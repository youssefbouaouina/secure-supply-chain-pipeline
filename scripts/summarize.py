#!/usr/bin/env python3
"""Turn raw scanner output in results/ into results/metrics.json and RESULTS.md.

Only reads files produced by scripts/scan.sh. Every number in RESULTS.md comes
from these files; nothing is typed by hand.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
SEVERITIES = ["Critical", "High", "Medium", "Low", "Negligible", "Unknown"]


def load_json(path: Path, default):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return default


def cve_counts(path: Path) -> dict[str, int]:
    data = load_json(path, {})
    counts = {severity: 0 for severity in SEVERITIES}
    for match in data.get("matches", []):
        severity = match.get("vulnerability", {}).get("severity", "Unknown")
        counts[severity] = counts.get(severity, 0) + 1
    counts["total"] = sum(counts.values())
    return counts


def unique_cves(path: Path) -> int:
    data = load_json(path, {})
    ids = {
        match.get("vulnerability", {}).get("id")
        for match in data.get("matches", [])
        if match.get("vulnerability", {}).get("id")
    }
    return len(ids)


def package_count(path: Path) -> int:
    data = load_json(path, {})
    return len(data.get("artifacts", []))


def size_bytes(path: Path) -> int | None:
    try:
        return int(path.read_text(encoding="utf-8").strip())
    except (OSError, ValueError):
        return None


def conftest_failures(path: Path) -> int:
    data = load_json(path, [])
    if isinstance(data, dict):
        data = data.get("failures", [])
    return sum(len(item.get("failures", [])) for item in data if isinstance(item, dict))


def kube_linter_findings(path: Path) -> int:
    data = load_json(path, {})
    if isinstance(data, dict):
        reports = data.get("Reports") or data.get("reports") or []
        if reports:
            return len(reports)
        checks = data.get("Checks") or []
        return sum(1 for check in checks if check.get("Status") not in (None, "pass"))
    if isinstance(data, list):
        return len(data)
    return 0


def mib(value: int | None) -> float | None:
    return round(value / (1024 * 1024), 1) if value else None


def build() -> dict:
    images = {}
    for version in ("v1", "v2"):
        images[version] = {
            "size_bytes": size_bytes(RESULTS / f"size-{version}.txt"),
            "size_mib": mib(size_bytes(RESULTS / f"size-{version}.txt")),
            "cves": cve_counts(RESULTS / f"grype-{version}.json"),
            "unique_cves": unique_cves(RESULTS / f"grype-{version}.json"),
            "sbom_packages": package_count(RESULTS / f"sbom-{version}.spdx.json"),
        }
    policy = {}
    for version in ("v1", "v2"):
        policy[version] = {
            "conftest_failures": conftest_failures(RESULTS / f"conftest-{version}.json"),
            "kube_linter_findings": kube_linter_findings(RESULTS / f"kubelinter-{version}.json"),
        }
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "images": images,
        "policy": policy,
    }


def write(metrics: dict) -> None:
    (RESULTS / "metrics.json").write_text(
        json.dumps(metrics, indent=2) + "\n", encoding="utf-8"
    )
    v1, v2 = metrics["images"]["v1"], metrics["images"]["v2"]
    p1, p2 = metrics["policy"]["v1"], metrics["policy"]["v2"]
    size_delta = None
    if v1["size_bytes"] and v2["size_bytes"]:
        size_delta = round((1 - v2["size_bytes"] / v1["size_bytes"]) * 100, 1)

    lines = [
        "# Results — secure-supply-chain-pipeline",
        "",
        f"Generated by `python scripts/summarize.py` at {metrics['generated_at']} (UTC) from the",
        "raw scanner files in this directory.",
        "",
        "| Metric | v1 (before) | v2 (hardened) |",
        "|---|---|---|",
        f"| Image size | {v1['size_mib']} MiB | {v2['size_mib']} MiB |",
        f"| Unique CVEs (Grype) | {v1['unique_cves']} | {v2['unique_cves']} |",
        f"| Critical | {v1['cves']['Critical']} | {v2['cves']['Critical']} |",
        f"| High | {v1['cves']['High']} | {v2['cves']['High']} |",
        f"| Medium | {v1['cves']['Medium']} | {v2['cves']['Medium']} |",
        f"| Low | {v1['cves']['Low']} | {v2['cves']['Low']} |",
        f"| SBOM packages (Syft) | {v1['sbom_packages']} | {v2['sbom_packages']} |",
        f"| Conftest policy failures | {p1['conftest_failures']} | {p2['conftest_failures']} |",
        f"| kube-linter findings | {p1['kube_linter_findings']} | {p2['kube_linter_findings']} |",
        "",
    ]
    if size_delta is not None:
        lines.append(f"Image size change: **-{size_delta}%**.")
        lines.append("")

    lines += [
        "## How this was produced",
        "",
        "```bash",
        "mvn -B -DskipTests package",
        "docker build -f Dockerfile.v1 -t app:v1 .",
        "docker build -f Dockerfile    -t app:v2 .",
        "bash scripts/scan.sh",
        "```",
        "",
        "Grype, Syft, Conftest and kube-linter versions are pinned in `.github/workflows/ci.yml`.",
        "The quality gate is `grype app:v2 --fail-on critical`; the pipeline fails if it finds one.",
        "",
    ]
    (RESULTS / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    write(build())
    print("results/metrics.json and results/RESULTS.md written")
